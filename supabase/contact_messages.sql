create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null check (char_length(trim(name)) between 1 and 100),
  email text not null check (char_length(trim(email)) between 3 and 320),
  message text not null check (char_length(trim(message)) between 1 and 5000)
);

alter table public.contact_messages enable row level security;

grant insert on table public.contact_messages to anon, authenticated;
grant usage, select on sequence public.contact_messages_id_seq to anon, authenticated;

drop policy if exists "Anyone can send a contact message" on public.contact_messages;
create policy "Anyone can send a contact message"
  on public.contact_messages for insert
  to anon, authenticated
  with check (
    char_length(trim(name)) between 1 and 100
    and char_length(trim(email)) between 3 and 320
    and char_length(trim(message)) between 1 and 5000
  );
